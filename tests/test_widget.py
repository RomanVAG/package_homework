        ("  Счет  12345678901234567890  ", "Счет **7890"),
        ("  Visa  1234567812345678  ", "Visa 1234 56** **** 5678"),
        ("  Карта  1234567812345678  ", "Карта 1234 56** **** 5678"),
        ("Карта  1234567812345678", "Карта 1234 56** **** 5678"),  # Двойной пробел
