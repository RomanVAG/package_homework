import pytest

from src.widget import mask_account_card, get_date


@pytest.mark.parametrize(
    "input_str, expected",
    [
        # Базовые случаи
        ("", ""),
        ("   ", "   "),
        ("Счет", "Счет"),
        ("Карта", "Карта"),

        # Тесты для счетов (разные форматы и регистры)
        ("Счет 12345678901234567890", "Счет **7890"),
        ("сЧет 12345678901234567890", "сЧет **7890"),
        ("СЧЕТ 12345678901234567890", "СЧЕТ **7890"),
        ("Счет 1234567890123456", "Счет **3456"),  # Нестандартная длина
        ("Счет 1234", "Счет 1234"),  # Не маскируется (слишком короткий)

        # Тесты для карт (разные платежные системы)
        ("Карта 1234567812345678", "Карта 1234 56** **** 5678"),
        ("Visa 1234567812345678", "Visa 1234 56** **** 5678"),
        ("Visa Platinum 1234567812345678", "Visa Platinum 1234 56** **** 5678"),
        ("MasterCard 1234567812345678", "MasterCard 1234 56** **** 5678"),
        ("МИР 1234567812345678", "МИР 1234 56** **** 5678"),
        ("American Express 1234567812345678", "American Express 1234 56** **** 5678"),
        ("JCB 1234567812345678", "JCB 1234 56** **** 5678"),

        # Неполные/некорректные номера карт
        ("Карта 1234", "Карта 1234"),  # Не маскируется
        ("Visa 12345678", "Visa 12345678"),  # Не маскируется
        ("Карта 123456781234567", "Карта 123456781234567"),  # 15 цифр (не маскируется)

        # Тесты с пробелами
        ("  Счет  12345678901234567890  ", "  Счет  **7890  "),
        ("  Visa  1234567812345678  ", "  Visa  1234 56** **** 5678  "),
        ("  Карта  1234567812345678  ", "  Карта  1234 56** **** 5678  "),

        # Комбинированные случаи
        ("Счет корпоративный 12345678901234567890", "Счет корпоративный **7890"),
        ("Карта зарплатная 1234567812345678", "Карта зарплатная 1234 56** **** 5678"),
        ("Доп. карта 1234567812345678", "Доп. карта 1234 56** **** 5678"),

        # Граничные случаи
        ("Счет 00000000000000000001", "Счет **0001"),
        ("Карта 0000111122223333", "Карта 0000 11** **** 3333"),
    ],
)
def test_mask_account_card(input_str, expected):
    """Проверяет корректность маскировки для различных типов карт и счетов."""
    assert mask_account_card(input_str) == expected


# Дополнительные тесты для проверки обработки ошибок
@pytest.mark.parametrize(
    "input_str, expected_exception",
    [
        ("Счет abcdef", ValueError),  # Некорректные символы в номере счета
        ("Карта 1234abcd5678efgh", ValueError),  # Некорректные символы в номере карты
        ("Карта 1234 5678 9012 3456", ValueError),  # Номера с пробелами
        (1234567812345678, ValueError),  # Числовой ввод (если функция не поддерживает)
    ]
)
def test_mask_account_card_errors(input_str, expected_exception):
    """Проверяет обработку некорректных входных данных."""
    with pytest.raises(expected_exception):
        mask_account_card(input_str)