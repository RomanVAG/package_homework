import pytest

from src.widget import mask_account_card, get_date

@pytest.mark.parametrize(
    "input_str, expected",
    [
        ("", ""),  # Пустая строка
        ("   ", "   "),  # Только пробелы
        ("Счет", "Счет"),  # Без номера (счет)
        ("Карта", "Карта"),  # Без номера (карта)
        ("Счет 12345678901234567890", "Счет **7890"),  # Маскировка счета
        ("счет 12345678901234567890", "счет **7890"),  # Проверка регистра
        ("Карта 1234567812345678", "Карта 1234 56** **** 5678"),  # Маскировка карты
        ("Visa Platinum 1234567812345678", "Visa Platinum 1234 56** **** 5678"),  # Длинное название
        ("МИР 1234567812345678", "МИР 1234 56** **** 5678"),  # Другая платежная система
        ("Счет 123", "Счет 123"),  # Слишком короткий счет
        ("Карта 1234", "Карта 1234"),  # Слишком короткая карта
        ("  Счет  12345678901234567890  ", "  Счет  **7890"),  # Лишние пробелы (счет)
        ("  Карта  1234567812345678  ", "  Карта  1234 56** **** 5678"),  # Лишние пробелы (карта)
    ],
)
def test_mask_account_card(input_str, expected):
    """Тестирует функцию mask_account_card с различными входными данными."""
    assert mask_account_card(input_str) == expected